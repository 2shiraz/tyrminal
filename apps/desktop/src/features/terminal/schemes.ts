export const DEFAULT_SCHEME_ID = "tyrminal-night";

export function schemeById(id: string): TerminalScheme {
  return SCHEMES.find((s) => s.id === id) ?? (SCHEMES[0] as TerminalScheme);
}

const ANSI_KEYS = ["red", "green", "yellow", "blue", "magenta", "cyan", "brightRed", "brightGreen", "brightYellow", "brightBlue", "brightMagenta", "brightCyan"] as const;

function luminance(hex: string): number {
  const n = Number.parseInt(hex.slice(1), 16);
  const channel = (v: number) => {
    const s = v / 255;
    return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
  };
  return 0.2126 * channel((n >> 16) & 255) + 0.7152 * channel((n >> 8) & 255) + 0.0722 * channel(n & 255);
}

export function contrast(a: string, b: string): number {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x) as [number, number];
  return (hi + 0.05) / (lo + 0.05);
}

/** ANSI colors of a scheme below 3:1 on its background, for the picker's honesty note. */
export function lowContrastColors(scheme: TerminalScheme): string[] {
  return ANSI_KEYS.filter((key) => contrast(scheme[key], scheme.background) < 3);
}
