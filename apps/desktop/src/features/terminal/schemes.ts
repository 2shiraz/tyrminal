// Built-in terminal color schemes. Independent of the application theme. Palettes of the
// well-known schemes follow their published values (MIT-licensed projects; see NOTICE), with the
// adjustments noted per scheme where a value failed our readability floor.
//
// scripts/check-contrast.mjs enforces, for every scheme: foreground and text-on-selection at
// WCAG AA (4.5:1); bright black (comments, hints) at least 2:1. The two Tyrminal schemes also
// keep every ANSI color at 3:1 or more. Lower-contrast ANSI colors of third-party schemes are
// reported in the picker rather than silently altered.

import type { ITheme } from "@xterm/xterm";

export interface TerminalScheme extends Required<
  Pick<
    ITheme,
    | "background"
    | "foreground"
    | "cursor"
    | "cursorAccent"
    | "selectionBackground"
    | "black"
    | "red"
    | "green"
    | "yellow"
    | "blue"
    | "magenta"
    | "cyan"
    | "white"
    | "brightBlack"
    | "brightRed"
    | "brightGreen"
    | "brightYellow"
    | "brightBlue"
    | "brightMagenta"
    | "brightCyan"
    | "brightWhite"
  >
> {
  id: string;
  name: string;
  kind: "dark" | "light";
  credit: string;
}

