#!/usr/bin/env node
// Regenerates packages/contracts/src/generated from the Rust IPC contract (crates/contracts).
//
//   node scripts/generate-contracts.mjs           regenerate
//   node scripts/generate-contracts.mjs --check   fail if the committed output is stale
//
// The generated directory is never edited by hand.

import { spawnSync } from "node:child_process";
import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(root, "packages", "contracts", "src", "generated");
const check = process.argv.includes("--check");

function generateInto(dir) {
  const r = spawnSync("cargo", ["test", "-q", "-p", "tyrminal-contracts", "export_bindings"], {
    cwd: root,
    env: { ...process.env, TS_RS_EXPORT_DIR: dir },
    encoding: "utf8",
  });
  if (r.status !== 0) {
    console.error(r.stdout, r.stderr);
    process.exit(1);
  }
  const files = readdirSync(dir).filter((f) => f.endsWith(".ts") && f !== "index.ts").sort();
  const barrel = [
    "// Generated by scripts/generate-contracts.mjs. Do not edit.",
    ...files.map((f) => `export type { ${f.slice(0, -3)} } from "./${f.slice(0, -3)}";`),
    "",
  ].join("\n");
  writeFileSync(join(dir, "index.ts"), barrel);
  return [...files, "index.ts"];
}

if (check) {
  const scratch = mkdtempSync(join(tmpdir(), "tyrminal-contracts-"));
  try {
    const fresh = generateInto(scratch);
    const committed = existsSync(target) ? readdirSync(target).filter((f) => f.endsWith(".ts")).sort() : [];
    const problems = [];
    if (fresh.slice().sort().join() !== committed.join()) problems.push("file list differs");
    for (const f of fresh) {
      const a = readFileSync(join(scratch, f), "utf8");
      const b = existsSync(join(target, f)) ? readFileSync(join(target, f), "utf8") : "";
      if (a !== b) problems.push(`${f} is stale`);
    }
    if (problems.length) {
      console.error(`generated contracts are out of date (run pnpm contracts):\n  ${problems.join("\n  ")}`);
      process.exit(1);
    }
    console.log(`contracts ok: ${fresh.length} files`);
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
} else {
  rmSync(target, { recursive: true, force: true });
  mkdirSync(target, { recursive: true });
  console.log(`generated ${generateInto(target).length} files in packages/contracts/src/generated`);
}
