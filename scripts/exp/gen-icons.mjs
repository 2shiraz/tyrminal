// Afterglow (experimental UI, branch only): generates apps/desktop/src/exp/ui/icons.tsx, the
// Phosphor (MIT) counterpart of main's Lucide set, with the same export names so the swap is
// invisible to the components. Build-time only: @phosphor-icons/core is a devDependency and the
// SVG path data is inlined, so nothing is fetched at run time.
//
//   node scripts/exp/gen-icons.mjs           write the file
//   node scripts/exp/gen-icons.mjs --check   fail if it is out of date or a name is unmapped

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const desktop = join(root, "apps", "desktop");
const assets = join(desktop, "node_modules", "@phosphor-icons", "core", "assets");
const outFile = join(desktop, "src", "exp", "ui", "icons.tsx");

