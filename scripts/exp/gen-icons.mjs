const mainIcons = readFileSync(join(desktop, "src", "components", "ui", "icons.tsx"), "utf8");
const names = [...mainIcons.matchAll(/export const (Icon\w+) = svg/g)].map((m) => m[1]);
const unmapped = names.filter((n) => !(n in MAP));
if (unmapped.length) {
  console.error(`no Phosphor icon for: ${unmapped.join(", ")} (add them to MAP in scripts/exp/gen-icons.mjs)`);
  process.exit(1);
}

function paths(weight, name) {
  const svg = readFileSync(join(assets, weight, weight === "regular" ? `${name}.svg` : `${name}-${weight}.svg`), "utf8");
  return [...svg.matchAll(/<path d="([^"]+)"(?: opacity="([^"]+)")?\/>/g)].map((m) => ({ d: m[1], opacity: m[2] }));
}

const lines = [
  "// Generated by scripts/exp/gen-icons.mjs from @phosphor-icons/core 2.1.1 (MIT License, Copyright (c)",
  "// 2023 Phosphor Icons). Experimental UI build only: swapped in for components/ui/icons.tsx with the",
  "// same export names. Inline SVG, nothing fetched at run time. Regenerate rather than hand-edit.",
  "",
  'import type { SVGProps } from "react";',
  "",
  'export type IconProps = Omit<SVGProps<SVGSVGElement>, "children"> & { size?: number };',
  "",
  "type Shape = readonly [d: string, opacity?: number];",
  "",
  "function svg(shapes: readonly Shape[]) {",
  "  return function Icon({ size = 16, ...rest }: IconProps) {",
  "    return (",
  '      <svg xmlns="http://www.w3.org/2000/svg" width={size} height={size} viewBox="0 0 256 256" fill="currentColor" aria-hidden="true" focusable="false" {...rest}>',
  "        {shapes.map(([d, opacity], i) => (",
  "          // Fixed geometry from the generated list; position is the identity.",
  "          <path key={i} d={d} opacity={opacity} />",
  "        ))}",
  "      </svg>",
  "    );",
  "  };",
  "}",
  "",
];
const encode = (list) => `[${list.map((p) => (p.opacity ? `[${JSON.stringify(p.d)}, ${p.opacity}]` : `[${JSON.stringify(p.d)}]`)).join(", ")}]`;
for (const name of names) lines.push(`export const ${name} = svg(${encode(paths("regular", MAP[name]))});`);
lines.push("");
lines.push("/** Duotone variants for the 40 px tiles (the second layer takes the tile's tint). */");
for (const [exp, ph] of [["DuoServer", "hard-drives"], ["DuoFolder", "folder"], ["DuoKey", "key"], ["DuoTerminal", "terminal-window"], ["DuoFingerprint", "fingerprint"], ["DuoScroll", "scroll"], ["DuoPath", "path"], ["DuoUser", "user"]]) {
  lines.push(`export const Icon${exp} = svg(${encode(paths("duotone", ph))});`);
}
lines.push("");
const out = lines.join("\n");

if (process.argv.includes("--check")) {
  if (readFileSync(outFile, "utf8") !== out) {
    console.error("apps/desktop/src/exp/ui/icons.tsx is out of date: run node scripts/exp/gen-icons.mjs");
    process.exit(1);
  }
  console.log("icons.tsx is up to date");
} else {
  writeFileSync(outFile, out);
  console.log(`wrote ${outFile} (${names.length} icons)`);
}
