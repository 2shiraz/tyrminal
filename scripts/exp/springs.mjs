#!/usr/bin/env node
// Afterglow (experimental UI, branch only): turns the spring table (apps/desktop/src/exp/motion/
// springs.json: a bounce and a total duration each) into CSS `linear()` easing curves and the
// matching Motion `visualDuration`, so CSS transitions and Motion springs share one source of
// truth (plan §5.1).
//
//   node scripts/exp/springs.mjs           write exp/styles/springs.css and exp/motion/springs.ts
//   node scripts/exp/springs.mjs --check   fail if either is out of date
//
// The physics are Motion's own mapping: stiffness = (2π / (1.2 · visualDuration))², mass 1,
// damping = 2 · clamp(0.05, 1, 1 − bounce) · √stiffness, starting at rest. A spring is settled once
// it is within 0.5% of its target and nearly still. Settling time scales linearly with
// visualDuration for a given bounce, so visualDuration is chosen to settle in exactly the duration
// the table asks for (main's motion rules cap a running animation at 220 ms).

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const table = JSON.parse(readFileSync(join(root, "apps/desktop/src/exp/motion/springs.json"), "utf8"));
const outFile = join(root, "apps/desktop/src/exp/styles/springs.css");
const tsFile = join(root, "apps/desktop/src/exp/motion/springs.ts");

export function simulate({ visualDuration, bounce }) {
  const stiffness = ((2 * Math.PI) / (visualDuration * 1.2)) ** 2;
  const damping = 2 * Math.min(1, Math.max(0.05, 1 - bounce)) * Math.sqrt(stiffness);
  const dt = 1 / 2000;
  let x = 0;
  let v = 0;
  let t = 0;
  const samples = [[0, 0]];
  // Semi-implicit Euler at 2 kHz: well under 0.1% error for these stiffnesses.
  while (t < 3) {
    const a = stiffness * (1 - x) - damping * v;
    v += a * dt;
    x += v * dt;
    t += dt;
    samples.push([t, x]);
    if (Math.abs(1 - x) < 0.005 && Math.abs(v) < 0.05) break;
  }
  return { duration: t, samples };
}

/** Down-samples to points whose straight segments stay within 0.002 of the curve. */
function toLinear({ duration, samples }) {
  const points = [samples[0]];
  let anchor = 0;
  for (let i = 2; i < samples.length; i += 1) {
    const [t0, x0] = samples[anchor];
    const [t1, x1] = samples[i];
    let ok = true;
    for (let j = anchor + 1; j < i; j += 1) {
      const [t, x] = samples[j];
      const expected = x0 + ((x1 - x0) * (t - t0)) / (t1 - t0);
      if (Math.abs(expected - x) > 0.002) {
        ok = false;
        break;
      }
    }
    if (!ok) {
      anchor = i - 1;
      points.push(samples[anchor]);
    }
  }
  points.push([duration, 1]);
  const stops = points.map(([t, x], i) => {
    const value = i === points.length - 1 ? "1" : (Math.round(x * 1000) / 1000).toString();
    if (i === 0) return "0";
    if (i === points.length - 1) return "1";
    return `${value} ${(Math.round((t / duration) * 1000) / 10).toString()}%`;
  });
  return `linear(${stops.join(", ")})`;
}

const kebab = (name) => name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

/** The visualDuration (s) whose spring settles in `ms`, found from one probe (linear scaling). */
function fit({ bounce, duration: ms }) {
  const probe = simulate({ visualDuration: 0.3, bounce });
  const visualDuration = Math.round(((0.3 * ms) / 1000 / probe.duration) * 10000) / 10000;
  const sim = simulate({ visualDuration, bounce });
  return { visualDuration, sim };
}
const fitted = {};
const lines = [
  "/* Generated by scripts/exp/springs.mjs from exp/motion/springs.json. Do not edit by hand. */",
  "",
  ":root[data-ui=\"afterglow\"] {",
];
const durations = [];
for (const [name, spec] of Object.entries(table)) {
  if (name.startsWith("/")) continue;
  const { visualDuration, sim } = fit(spec);
  const ms = spec.duration;
  fitted[name] = { visualDuration, bounce: spec.bounce, duration: ms };
  lines.push(`  /* ${name}: bounce ${spec.bounce}, ${ms} ms (Motion visualDuration ${visualDuration}s) */`);
  lines.push(`  --spring-${kebab(name)}: ${toLinear(sim)};`);
  lines.push(`  --spring-${kebab(name)}-duration: ${ms}ms;`);
  durations.push(`  --spring-${kebab(name)}-duration: 0ms;`);
}
lines.push("}", "");
lines.push("/* Reduced motion (the OS setting or the in-app switch): every spring is instant. */");
lines.push("@media (prefers-reduced-motion: reduce) {", "  :root[data-ui=\"afterglow\"] {", ...durations.map((l) => `  ${l}`), "  }", "}", "");
lines.push(":root[data-ui=\"afterglow\"][data-reduce-motion=\"true\"] {", ...durations, "}", "");
const css = lines.join("\n");

const ts = [
  "// Generated by scripts/exp/springs.mjs from springs.json. Do not edit by hand.",
  "// Motion spring options matching the CSS linear() curves in exp/styles/springs.css.",
  "",
  "export interface Spring {",
  "  readonly type: \"spring\";",
  "  readonly visualDuration: number;",
  "  readonly bounce: number;",
  "  /** Total duration in ms, settle included (main's motion rules cap it at 220). */",
  "  readonly duration: number;",
  "}",
  "",
  "export const SPRINGS = {",
  ...Object.entries(fitted).map(([n, f]) => `  ${n}: { type: "spring", visualDuration: ${f.visualDuration}, bounce: ${f.bounce}, duration: ${f.duration} },`),
  "} as const satisfies Record<string, Spring>;",
  "",
].join("\n");

if (process.argv.includes("--check")) {
  for (const [file, text] of [[outFile, css], [tsFile, ts]]) {
    if (readFileSync(file, "utf8") !== text) {
      console.error(`${file} is out of date: run node scripts/exp/springs.mjs`);
      process.exit(1);
    }
  }
  console.log("springs.css and springs.ts are up to date");
} else {
  writeFileSync(outFile, css);
  writeFileSync(tsFile, ts);
  console.log(`wrote ${outFile} and ${tsFile}`);
}
