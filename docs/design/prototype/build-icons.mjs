// Writes icons.js: the app's own Lucide subset (apps/desktop/src/components/ui/icons.tsx) as an inline
// SVG sprite for the static prototype, so the mock-ups use the exact icons the app ships.
//   node docs/design/prototype/build-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(join(here, "../../../apps/desktop/src/components/ui/icons.tsx"), "utf8");
const symbols = [];
for (const m of src.matchAll(/export const Icon(\w+) = svg\(\[(.*)\]\);/g)) {
  const id = m[1].replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
  const shapes = [...m[2].matchAll(/"([^"]+)"/g)].map(([, d]) => {
    const [tag, ...pairs] = d.split("|");
    const attrs = pairs.map((p) => { const i = p.indexOf("="); return `${p.slice(0, i)}="${p.slice(i + 1)}"`; }).join(" ");
    return `<${tag} ${attrs}/>`;
  });
  symbols.push(`<symbol id="i-${id}" viewBox="0 0 24 24">${shapes.join("")}</symbol>`);
}
const sprite = `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">${symbols.join("")}</svg>`;
writeFileSync(join(here, "icons.js"), `// Generated by build-icons.mjs from the app's icon set. Do not edit.\ndocument.body.insertAdjacentHTML("afterbegin", ${JSON.stringify(sprite)});\n`);
console.log(`${symbols.length} icons`);
